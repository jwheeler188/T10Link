#!/usr/bin/env python3
"""
Generates the Savant Blueprint component profile from the bridge's state
definitions, so the profile's status parsers always match what the bridge sends.

    python3 generate_profile.py              -> blueprint-import/: honeywell_t10link.xml,
                                                honeywell_t10link.htm (Documentation tab, from MANUAL.md + STATES.md)
                                                and honeywell_t10link.icns side by side
    python3 generate_profile.py --sensors 6  -> more room-sensor slots (set max_sensors in config.json to match)
    python3 generate_profile.py --thermostats 12 -> state parsers for more thermostats (default 8, up to 16)

Structure:
  * Ethernet/TCP control to the T10Link bridge, KEY=value status lines: same proven layout as
    Savant OpenWx and HaloKey.
  * Native Savant HVAC service, laid out like Savant's own Honeywell T-Series (v1.4) and Venstar
    ColorTouch profiles: device_class HVAC_controller, internal "HVAC Controller" with
    ENV_HVACCONTROLLER_SOURCE, the standard HVAC actions with ThermostatAddress / ThermostatAddress2,
    a Zone entity, and Savant's state names (ThermostatCurrentTemperature_1, ThermostatMode_1,
    IsCurrentHVACModeHeat_1, IsW1RelayEnergized_1, ...).
  * Several thermostats on one component (like Savant's multi-zone HVAC profiles, e.g. Lutron
    RadioRA2): every HVAC action sends its ThermostatAddress ("@2:SETHEAT:70", no spaces in any
    parameter), the Zone entity allows one HVAC data table row per thermostat, and thermostat n's
    states end in _n (ThermostatMode_2) or start with Tn_ (T2_MODE).
  * No fan actions: HomeKit on the T9/T10 doesn't expose fan mode.
  * Custom actions + T_* / SENSORn_* states for triggers, custom screens and what the native
    service doesn't cover (room sensors, filter reminders, occupancy).
"""
