def body(model, sensors, thermostats, defs):
    return "\n".join([
        head(model, sensors, thermostats),
        f'    <logical_component logical_component_name="{LC}">',
        "        <implementation>",
        '            <internal name_on_component="HVAC Controller"/>',
        "        </implementation>",
        status_messages(defs),
        hvac_resource(thermostats),
        custom_actions(),
        "    </logical_component>",
        "</component>",
        "",
    ])


def build(sensors, thermostats):
    defs = state_defs(sensors, thermostats)
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(body(MODEL, sensors, thermostats, defs), encoding="utf-8")
    print(f"wrote {OUT.relative_to(HERE)}: {thermostats} thermostats x {sensors} sensor slots, {len(defs)} status parsers")


